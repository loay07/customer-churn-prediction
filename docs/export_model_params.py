"""Export the trained pipeline's fitted parameters to JSON for the static,
client-side demo in docs/index.html.

GitHub Pages only serves static files — it can't run the FastAPI backend, so
the docs/ site can't call POST /predict. Since the final model is a plain
logistic regression over one-hot-encoded and standard-scaled inputs, its
entire decision function is just a dot product plus a sigmoid. This script
reads that dot product's actual fitted weights (from the same
models/churn_logistic_model.joblib used by the API) into model_params.js, a
small generic data file that docs/model.js evaluates in the browser. The
model itself is not changed or retrained — this only re-expresses its
existing fitted parameters for a JS runtime instead of a Python one.

Run from the project root:

    python docs/export_model_params.py
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib

MODEL_PATH = Path(__file__).resolve().parents[1] / "models" / "churn_logistic_model.joblib"
METADATA_PATH = Path(__file__).resolve().parents[1] / "models" / "model_metadata.json"
OUTPUT_PATH = Path(__file__).resolve().parent / "model_params.js"

MEDIUM_RISK_CUTOFF = 0.60  # must match src/churn_model.py


def export() -> None:
    pipeline = joblib.load(MODEL_PATH)
    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))

    preprocessor = pipeline.named_steps["preprocessor"]
    classifier = pipeline.named_steps["model"]

    feature_names = list(preprocessor.get_feature_names_out())
    coefficients = classifier.coef_[0]
    assert len(feature_names) == len(coefficients)

    fitted_transformers = {name: (transformer, columns) for name, transformer, columns in preprocessor.transformers_}
    onehot_encoder, onehot_columns = fitted_transformers["categorical"]
    scaler, scaled_columns = fitted_transformers["numerical"]

    terms = []
    coef_index = 0

    # OneHotEncoder lays out its output as each input column's categories, in
    # order, one after another — exactly the nesting below — so walking
    # onehot_columns / categories_ in lockstep with the coefficient array
    # lines each coefficient up with the (field, category) it belongs to.
    for column, categories in zip(onehot_columns, onehot_encoder.categories_):
        for category in categories:
            terms.append(
                {
                    "type": "onehot",
                    "field": column,
                    "value": category.item() if hasattr(category, "item") else category,
                    "coef": float(coefficients[coef_index]),
                }
            )
            coef_index += 1

    num_onehot_terms = coef_index
    numerical_coefs = coefficients[num_onehot_terms:]
    for column, mean, scale, coef in zip(
        scaled_columns, scaler.mean_, scaler.scale_, numerical_coefs
    ):
        terms.append(
            {
                "type": "scaled",
                "field": column,
                "mean": float(mean),
                "scale": float(scale),
                "coef": float(coef),
            }
        )

    # Cross-check the order we just built against the pipeline's own
    # authoritative output-column order, so a future sklearn version that
    # lays out ColumnTransformer output differently fails loudly here
    # instead of silently misaligning coefficients with fields in the browser.
    expected_names = [n.split("__", 1)[1] for n in feature_names]
    actual_names = [f"{t['field']}_{t['value']}" for t in terms if t["type"] == "onehot"]
    actual_names += [t["field"] for t in terms if t["type"] == "scaled"]
    assert actual_names == expected_names, (
        "Reconstructed feature order does not match the fitted pipeline's "
        f"get_feature_names_out(). Expected {expected_names}, got {actual_names}."
    )

    payload = {
        "model_type": metadata["model_type"],
        "threshold": metadata["threshold"],
        "medium_risk_cutoff": MEDIUM_RISK_CUTOFF,
        "intercept": float(classifier.intercept_[0]),
        "terms": terms,
    }

    js_source = (
        "// Auto-generated by docs/export_model_params.py - do not edit by hand.\n"
        "// Re-run that script after retraining models/churn_logistic_model.joblib.\n"
        f"const CHURN_MODEL_PARAMS = {json.dumps(payload, indent=2)};\n"
        "\n"
        "// Support both a plain <script src> global (for the browser) and\n"
        "// CommonJS require() (for the Node-based test in tests/test_docs_model_js.py).\n"
        'if (typeof module !== "undefined" && module.exports) {\n'
        "  module.exports = CHURN_MODEL_PARAMS;\n"
        "}\n"
    )
    OUTPUT_PATH.write_text(js_source, encoding="utf-8")
    print(f"Wrote {len(terms)} terms to {OUTPUT_PATH}")


if __name__ == "__main__":
    export()
